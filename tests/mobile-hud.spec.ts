import { expect, test } from "@playwright/test";

test("REBORN mobile HUD has usable thumb controls without a ten-slot screen takeover", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));

  await page.goto("/?debug=1&lang=th", { waitUntil: "domcontentloaded" });
  await page.locator("#gv-play").click();
  await page.locator("[data-action='create-slot']").first().click();
  await page.locator("#gv-name").fill("RebornTouch");
  await page.locator("#gv-create-character").click();
  await page.locator("[data-action='skip-cutscene']").click();

  await expect(page.locator("#rpg canvas")).toBeVisible({ timeout: 30_000 });
  await expect(page.locator("body")).toHaveClass(/gv-compact-hud/);
  const hotbar = page.locator("#gv-skill-hotbar");
  await expect(hotbar).toBeVisible();
  await expect(hotbar).toHaveAttribute("data-page", "0");
  await expect(page.locator(".gv3-hotbar-slot:visible")).toHaveCount(3);
  await expect(page.locator("[data-hotbar-page-next]")).toBeVisible();

  // Real hotbar buttons continue to be generated by the existing skill system.
  // The extra control changes only which three of the ten are displayed.
  await page.locator("[data-hotbar-page-next]").click();
  await expect(hotbar).toHaveAttribute("data-page", "1");
  await expect(page.locator(".gv3-hotbar-slot:visible")).toHaveCount(3);
  await page.locator("[data-hotbar-page-next]").click();
  await expect(hotbar).toHaveAttribute("data-page", "2");
  await page.locator("[data-hotbar-page-next]").click();
  await expect(hotbar).toHaveAttribute("data-page", "3");
  await expect(page.locator(".gv3-hotbar-slot:visible")).toHaveCount(1);
  await page.locator("[data-hotbar-page-next]").click();
  await expect(hotbar).toHaveAttribute("data-page", "0");

  await expect(page.locator("[data-combat='attack']")).toBeVisible();
  await expect(page.locator("[data-combat='target']")).toBeVisible();
  await expect(page.locator("[data-combat='auto']")).toBeVisible();
  await expect(page.locator("[data-combat='loot']")).toBeHidden();
  // Auto-loot has not been removed; its real setting remains inside the full menu.
  await page.locator("#gv-menu-btn").click();
  await page.locator("#gv-combat-btn").click();
  await expect(page.locator("[data-setting-loot]")).toBeAttached();

  // The HUD button must issue the actual combat event rather than a visual-only demo.
  await page.locator("[data-combat-close]").click();
  await page.locator("#gv-resume").click();
  await page.evaluate(() => {
    (window as any).__GV_REBORN_ATTACK_TAPS__ = 0;
    window.addEventListener("greenvale:basic-attack", () => {
      (window as any).__GV_REBORN_ATTACK_TAPS__ += 1;
    });
  });
  await page.locator("[data-combat='attack']").click();
  await expect.poll(() => page.evaluate(() => (window as any).__GV_REBORN_ATTACK_TAPS__)).toBe(1);

  const dock = await hotbar.boundingBox();
  const combat = await page.locator("#gv-combat-controls").boundingBox();
  expect(dock && combat).toBeTruthy();
  // Compact hotbar is physically above the right combat cluster, not on top of it.
  expect((dock?.y || 0) + (dock?.height || 0)).toBeLessThanOrEqual((combat?.y || 0) + 2);

  await expect(page.locator("#runtime-error")).toBeHidden();
  expect(errors.filter(message => /applySyncPacket|module script|RPGJS .*BOOT ERROR/i.test(message))).toEqual([]);
});
